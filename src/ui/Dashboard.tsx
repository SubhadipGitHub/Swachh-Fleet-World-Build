// --- Process tracker (D-5) ----------------------------------------------------------------------------------------

export function Tracker({ subject }: { subject: string | null }): JSX.Element {
  const d = store.dashboard.value;
  const timeline = d?.tracker.timeline ?? null;
  return (
    <section class="tracker panel" aria-label="Process tracker">
      <header>
        Process tracker <span class="dim">· {timeline && subject ? subject : 'Today'}</span>
      </header>
      <ol>
        {TRACKER_STEPS.map((step, i) => {
          const value = timeline ? hhmm(timeline[i]?.at ?? null) : fmt(d?.tracker.counts[step] ?? 0);
          const done = timeline ? (timeline[i]?.at ?? null) !== null : true;
          return (
            <li key={step} data-step={step} class={done ? 'done' : ''}>
              <span class="step-name">{step}</span>
              <span class="step-value">{value}</span>
            </li>
          );
        })}
      </ol>
    </section>
  );
}

// --- Live tables (D-6) --------------------------------------------------------------------------------------------

interface Column {
  readonly key: string;
  readonly label: string;
  readonly format?: (v: Row[string]) => string;
}

const num1 = (v: Row[string]): string => (typeof v === 'number' ? fmt(v, 1) : '—');
const num0 = (v: Row[string]): string => (typeof v === 'number' ? fmt(v) : '—');
const time = (v: Row[string]): string => hhmm(typeof v === 'number' ? v : null);

const COLUMNS: Readonly<Record<TableTab, readonly Column[]>> = {
  bins: [
    { key: 'displayId', label: 'ID' },
    { key: 'kind', label: 'Type' },
    { key: 'ward', label: 'Ward' },
    { key: 'reportedPct', label: 'Fill %', format: num0 },
    { key: 'predictedFullAt', label: 'Predicted full', format: time },
    { key: 'lastServicedAt', label: 'Last serviced', format: time },
    { key: 'sensorStatus', label: 'Sensor' },
  ],
  fleet: [
    { key: 'displayId', label: 'Vehicle' },
    { key: 'kind', label: 'Type' },
    { key: 'state', label: 'Status' },
    { key: 'loadKg', label: 'Load kg', format: num0 },
    { key: 'fuelLitres', label: 'Fuel L', format: num1 },
    { key: 'kmToday', label: 'Km today', format: num1 },
    { key: 'skippedToday', label: 'Skipped', format: num0 },
  ],
  routes: [
    { key: 'routeId', label: 'Route' },
    { key: 'vehicleDisplayId', label: 'Vehicle' },
    { key: 'stops', label: 'Stops' },
    { key: 'kmPlanned', label: 'Km planned', format: num1 },
    { key: 'kmActual', label: 'Km actual', format: num1 },
    { key: 'deviations', label: 'Deviations', format: num0 },
    { key: 'etaAt', label: 'ETA', format: time },
    { key: 'policy', label: 'Policy' },
    { key: 'replans', label: 'Re-plans', format: num0 },
  ],
};

const TAB_LABELS: Readonly<Record<TableTab, string>> = { bins: 'Bins & points', fleet: 'Fleet', routes: 'Routes' };

function tableRows(tab: TableTab): (Row & { __select: number })[] {
  const d = store.dashboard.value;
  if (!d) return [];
  if (tab === 'bins') {
    return d.tables.bins.map((r) => ({
      __select: r.binIndex,
      displayId: r.displayId,
      kind: KIND_LABELS[r.kind] ?? r.kind,
      ward: r.ward,
      reportedPct: r.reportedPct,
      predictedFullAt: r.predictedFullAt,
      lastServicedAt: r.lastServicedAt,
      sensorStatus: r.sensorStatus,
    }));
  }
  if (tab === 'fleet') {
    return d.tables.fleet.map((r) => ({
      __select: r.vehicleIndex,
      displayId: r.displayId,
      kind: KIND_LABELS[r.kind] ?? r.kind,
      state: stateLabel(r.state),
      loadKg: r.loadKg,
      fuelLitres: r.fuelLitres,
      kmToday: r.kmToday,
      skippedToday: r.skippedToday,
    }));
  }
  return d.tables.routes.map((r) => ({
    __select: r.vehicleIndex,
    routeId: r.routeId,
    vehicleDisplayId: r.vehicleDisplayId,
    stops: `${r.stopsDone} / ${r.stopsPlanned}`,
    kmPlanned: r.kmPlanned,
    kmActual: r.kmActual,
    deviations: r.deviations,
    etaAt: r.etaAt,
    policy: r.policy === 'dynamic' ? 'Dynamic' : 'Static',
    replans: r.replans,
  }));
}

export function Tables({ onSelect }: { onSelect: (sel: Selection) => void }): JSX.Element {
  const tab = store.tableTab.value;
  const [filter, setFilter] = useState('');
  const [sort, setSort] = useState<{ key: string; dir: SortDir } | null>(null);
  const columns = COLUMNS[tab];
  let rows = filterRows(tableRows(tab), filter);
  if (sort) rows = sortRows(rows, sort.key, sort.dir);
  return (
    <section class="tables panel">
      <div class="tables-head">
        <div role="tablist" aria-label="Live tables">
          {(Object.keys(TAB_LABELS) as TableTab[]).map((t) => (
            <button
              type="button"
              role="tab"
              key={t}
              id={`tab-${t}`}
              aria-selected={tab === t}
              aria-controls="tables-panel"
              onClick={() => {
                store.tableTab.value = t;
                setSort(null);
              }}
            >
              {TAB_LABELS[t]}
            </button>
          ))}
        </div>
        <input
          type="text"
          class="filter"
          aria-label="Filter rows"
          placeholder="Filter rows"
          value={filter}
          onInput={(e) => {
            setFilter(e.currentTarget.value);
          }}
        />
      </div>
      <div role="tabpanel" id="tables-panel" aria-labelledby={`tab-${tab}`} class="table-scroll">
        <table>
          <thead>
            <tr>
              {columns.map((c) => (
                <th key={c.key} scope="col" aria-sort={sort?.key === c.key ? (sort.dir === 'asc' ? 'ascending' : 'descending') : 'none'}>
                  <button
                    type="button"
                    onClick={() => {
                      setSort(sort?.key === c.key && sort.dir === 'asc' ? { key: c.key, dir: 'desc' } : { key: c.key, dir: 'asc' });
                    }}
                  >
                    {c.label}
                    {sort?.key === c.key ? (sort.dir === 'asc' ? ' ▲' : ' ▼') : ''}
                  </button>
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((r) => (
              <tr
                key={`${tab}-${r.__select}`}
                tabIndex={0}
                onClick={() => {
                  onSelect(tab === 'bins' ? { kind: 'bin', index: r.__select } : { kind: 'vehicle', index: r.__select });
                }}
                onKeyDown={(e) => {
                  if (e.key === 'Enter') onSelect(tab === 'bins' ? { kind: 'bin', index: r.__select } : { kind: 'vehicle', index: r.__select });
                }}
              >
                {columns.map((c) => (
                  <td key={c.key} data-col={c.key}>
                    {c.format ? c.format(r[c.key] ?? null) : String(r[c.key] ?? '—')}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

// --- Alerts (D-8) -------------------------------------------------------------------------------------------------

function alertText(a: Alert): string {
  const view = store.view.value;
  const vehicle = (id: number): string => view?.vehicles[id]?.displayId ?? `vehicle ${id}`;
  const bin = (id: number): string => view?.bins[id]?.displayId ?? `${id}`;
  switch (a.kind) {
    case 'bin-high':
      return `Bin ${bin(a.target.id)} at 90% or more`;
    case 'bin-overflow':
      return `Bin ${bin(a.target.id)} overflowing`;
    case 'black-spot':
      return `Black spot ${view?.blackSpots[a.target.id]?.displayId ?? a.target.id} activated`;
    case 'absent':
      return `${vehicle(a.target.id)} absent today`;
    case 'breakdown':
      return `${vehicle(a.target.id)} broke down`;
    case 'skips':
      return `${vehicle(a.target.id)} skipped 3 or more stops`;
    case 'deviation':
      return `${vehicle(a.target.id)} left its route`;
    case 'kcdc-cap':
      return 'KCDC at its intake cap: loads diverted to the landfill';
    case 'road-closed':
      return `Road closed by waterlogging (flood spot ${a.target.id + 1})`;
    case 'sensor-offline':
      return `Sensor offline at bin ${bin(a.target.id)}`;
    case 'replanned':
      return `Re-planned: ${a.detail ?? 'incident'}`;
    case 'plan-failed':
      return `Dynamic plan failed (${a.detail ?? 'solver error'}): static beats today`;
    case 'fairness':
      return `${a.detail ?? 'Some'} streets at risk of 48 h without collection`;
  }
}

export function AlertsList({ onPick }: { onPick: (a: Alert) => void }): JSX.Element {
  const alerts = store.alerts.value;
  return (
    <section class="alerts-panel panel">
      <header>Alerts</header>
      {alerts.length === 0 ? <p class="dim">No alerts yet.</p> : null}
      <ul aria-label="Alerts">
        {alerts.map((a) => (
          <li
            key={a.id}
            class={`alert alert-${a.severity}`}
            tabIndex={0}
            onClick={() => {
              onPick(a);
            }}
            onKeyDown={(e) => {
              if (e.key === 'Enter') onPick(a);
            }}
          >
            <span class="alert-time">{hhmm(a.t)}</span>
            <span class="alert-text">{alertText(a)}</span>
          </li>
        ))}
      </ul>
    </section>
  );
}

// --- Search (D-2) -------------------------------------------------------------------------------------------------

const SEARCH_KIND_LABEL: Readonly<Record<SearchEntry['kind'], string>> = {
  vehicle: 'Vehicle',
  bin: 'Bin',
  blackSpot: 'Black spot',
  facility: 'Facility',
  street: 'Street',
  ward: 'Ward',
};

export function SearchBox({ onPick }: { onPick: (e: SearchEntry) => void }): JSX.Element {
  const [query, setQuery] = useState('');
  const [active, setActive] = useState(0);
  const index = store.searchIndex.value;
  const results = index && query.trim() ? search(index, query) : [];
  const open = results.length > 0;
  const pick = (e: SearchEntry): void => {
    onPick(e);
    setQuery('');
  };
  return (
    <div class="search">
      <input
        type="text"
        role="combobox"
        aria-label="Search"
        aria-expanded={open}
        aria-controls="search-results"
        aria-autocomplete="list"
        placeholder="Search vehicle, bin, street, ward"
        value={query}
        onInput={(e) => {
          setQuery(e.currentTarget.value);
          setActive(0);
        }}
        onKeyDown={(e) => {
          if (e.key === 'ArrowDown') setActive(Math.min(results.length - 1, active + 1));
          else if (e.key === 'ArrowUp') setActive(Math.max(0, active - 1));
          else if (e.key === 'Enter' && results[active]) pick(results[active]);
          else if (e.key === 'Escape') setQuery('');
        }}
      />
      {open ? (
        <ul role="listbox" id="search-results" class="search-results panel">
          {results.map((r, i) => (
            <li
              role="option"
              key={`${r.kind}-${r.ref}`}
              aria-selected={i === active}
              onMouseDown={(e) => {
                e.preventDefault();
                pick(r);
              }}
            >
              {r.label}
              <span class="dim"> · {SEARCH_KIND_LABEL[r.kind]}</span>
            </li>
          ))}
        </ul>
      ) : null}
    </div>
  );
}

