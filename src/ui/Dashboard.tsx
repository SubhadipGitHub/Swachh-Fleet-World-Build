export type TagKind = 'Simulated' | 'Real' | 'Assumed' | 'Derived';

/** Provenance badge (P-2): every live number in the UI says where it comes from. */
export function Tag({ kind }: { kind: TagKind }): JSX.Element {
  const title = {
    Simulated: 'Generated by the seeded simulation (synthetic)',
    Real: 'Taken from a published source (see Data sources)',
    Assumed: 'A reasoned default where no public figure exists',
    Derived: 'Calculated from published figures',
  }[kind];
  return (
    <span class={`tag tag-${kind.toLowerCase()}`} title={title}>
      {kind}
    </span>
  );
}

const TAG_OF = { real: 'Real', assumed: 'Assumed', derived: 'Derived', synthetic: 'Simulated' } as const;

/** "HH:MM" of a sim time (IST), or a dash. */
function hhmm(t: number | null): string {
  if (t === null) return '—';
  const s = ((t % 86_400) + 86_400) % 86_400;
  return `${String(Math.floor(s / 3600)).padStart(2, '0')}:${String(Math.floor((s % 3600) / 60)).padStart(2, '0')}`;
}

// --- KPI cards (D-3) ----------------------------------------------------------------------------------------------

function Sparkline({ values }: { values: readonly (number | null)[] }): JSX.Element {
  const pts = values.map((v, i) => [i, v] as const).filter((p): p is readonly [number, number] => p[1] !== null);
  let path = '0,12 100,12';
  if (pts.length >= 2) {
    const min = Math.min(...pts.map((p) => p[1]));
    const max = Math.max(...pts.map((p) => p[1]));
    const span = max - min || 1;
    const n = Math.max(1, values.length - 1);
    path = pts.map(([i, v]) => `${((i / n) * 100).toFixed(1)},${(22 - ((v - min) / span) * 20).toFixed(1)}`).join(' ');
  }
  return (
    <svg class="sparkline" viewBox="0 0 100 24" preserveAspectRatio="none" aria-hidden="true">
      <polyline points={path} fill="none" stroke="currentColor" stroke-width="1.6" vector-effect="non-scaling-stroke" />
    </svg>
  );
}

function Delta({ live, twin, unit, digits, lowerIsBetter }: { live: number | null; twin: number | null; unit: string; digits: number; lowerIsBetter: boolean }): JSX.Element {
  const abs = live !== null && twin !== null ? deltaVsTwin(live, twin).abs : 0;
  const tiny = Math.abs(abs) < 0.5 * 10 ** -digits;
  const good = tiny ? 'same' : (abs < 0) === lowerIsBetter ? 'good' : 'bad';
  return (
    <div class={`kpi-delta delta-${good}`} title="Live world against the baseline twin (Static routes, same weather and conditions)">
      {tiny ? 'Same as baseline' : `${abs > 0 ? '+' : '−'}${fmt(Math.abs(abs), digits)}${unit} vs baseline`}
    </div>
  );
}

